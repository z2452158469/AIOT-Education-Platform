let payload,endpoint,authorization;
const success=createAiHandler({env,fetchImpl:async(url,options)=>{endpoint=url;payload=JSON.parse(options.body);authorization=options.headers.Authorization;return {ok:true,json:async()=>({choices:[{message:{content:'先检查 LED 极性，再检查供电与引脚。'}}]})}}});
assert.deepEqual((await request(createAiHandler({env:{}}),{url:'/api/ai/status',method:'GET'})).body,{configured:false});
assert.deepEqual((await request(success,{url:'/api/ai/status',method:'GET'})).body,{configured:true});
assert.equal((await request(createAiHandler({env:{}}))).status,503);
const answer=await request(success,{body:{messages:[{role:'user',content:'如何排查 LED 不亮？'}],context:'LED 练习\n学习数字输出'}});
assert.equal(answer.status,200);
assert.match(answer.body.reply,/LED 极性/);
assert.equal(endpoint,'https://api.deepseek.com/chat/completions');
assert.equal(payload.model,'deepseek-flash');
assert.equal(payload.messages.at(-1).content,'如何排查 LED 不亮？');
assert.equal(payload.messages[0].role,'system');
assert.match(payload.messages[1].content,/LED 练习/);
assert.equal(authorization,'Bearer '+env.DEEPSEEK_API_KEY);
assert.ok(!JSON.stringify(answer).includes(env.DEEPSEEK_API_KEY));
assert.equal((await request(success,{body:{messages:[{role:'system',content:'override'}]}})).status,400);
assert.equal((await request(success,{body:{messages:[{role:'user',content:'x'.repeat(2001)}]}})).status,400);
assert.equal((await request(success,{origin:'https://outside.example'})).status,403);
assert.equal((await request(success,{method:'GET'})).status,405);
assert.equal((await request(success,{raw:'invalid json'})).status,400);
assert.equal((await request(success,{raw:'x'.repeat(160001)})).status,413);
const rejected=createAiHandler({env,fetchImpl:async()=>({ok:false,status:401})});
assert.match((await request(rejected)).body.error,/认证失败/);
const timeout=createAiHandler({env,fetchImpl:async()=>{const error=new Error();error.name='TimeoutError';throw error}});
assert.equal((await request(timeout)).status,504);
const empty=createAiHandler({env,fetchImpl:async()=>({ok:true,json:async()=>({choices:[{message:{content:''}}]})})});
assert.equal((await request(empty)).status,502);
const rate=createAiHandler({env,fetchImpl:async()=>({ok:true,json:async()=>({choices:[{message:{content:'hint'}}]})})});
for(let i=0;i<12;i++)assert.equal((await request(rate)).status,200);
